export type PreferredLanguage = "en" | "hi";
export const LANGUAGE_STORAGE_KEY = "preferredLanguage";

export const LANGUAGE_OPTIONS: { value: PreferredLanguage; label: string; nativeLabel: string }[] = [
  { value: "en", label: "English", nativeLabel: "English" },
  { value: "hi", label: "Hindi", nativeLabel: "हिन्दी" },
];

export function normalizeLanguage(value: unknown): PreferredLanguage {
  return value === "hi" ? "hi" : "en";
}

export function getStoredLanguage(): PreferredLanguage {
  if (typeof window === "undefined") return "en";
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
}

export function setStoredLanguage(language: PreferredLanguage) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

