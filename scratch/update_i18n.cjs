// Parse the UI_TRANSLATIONS block
const dictMatch = content.match(/(const UI_TRANSLATIONS: Record<string, string> = \{)([\s\S]*?)(\};)/);
if (!dictMatch) {
  console.error('Could not find UI_TRANSLATIONS block');
  process.exit(1);
}

const prefix = dictMatch[1];
const innerContent = dictMatch[2];
const suffix = dictMatch[3];

// Parse existing key-value pairs
const existingPairs = {};
const lines = innerContent.split('\n');
lines.forEach(line => {
  const match = line.match(/^\s*"(.*?)":\s*"(.*?)",?\s*$/);
  if (match) {
    existingPairs[match[1]] = match[2];
  }
});

// Merge
const merged = { ...existingPairs, ...NEW_TRANSLATIONS };

// Reconstruct inner content
let newInnerContent = '\n';
Object.entries(merged).sort((a, b) => a[0].localeCompare(b[0])).forEach(([k, v]) => {
  newInnerContent += `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
});

const newContent = content.replace(dictMatch[0], prefix + newInnerContent + suffix);
